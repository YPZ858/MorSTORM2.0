"""Optional upstream localization adapters for the standalone pipeline.

CLI: python -m morstorm_b.localize settings.json
All camera parameters must be supplied from the acquisition calibration.
"""
from pathlib import Path
import argparse
import base64
import json
import os
import subprocess
import numpy as np
from .bridge import resource, _version


def localize(config):
    cfg = dict(config)
    inp, output = Path(cfg["input"]).resolve(), Path(cfg["output"]).resolve()
    if output.exists():
        raise FileExistsError(output)
    if cfg["backend"] == "picasso":
        from picasso import io, localize as api
        camera = cfg["camera"]
        values = [camera[k] for k in ("baseline", "sensitivity", "gain")]
        if not np.isfinite(values).all() or min(values[1:]) <= 0:
            raise ValueError("Invalid camera calibration")
        pixel = float(cfg["pixel_size_nm"])
        if not np.isfinite(pixel) or pixel <= 0:
            raise ValueError("Positive pixel_size_nm required")
        box = int(cfg["box_size"])
        if box < 3 or box % 2 == 0 or box != cfg["box_size"]:
            raise ValueError("box_size must be an odd integer >=3")
        movie, info = io.load_movie(str(inp))
        try:
            identifications = api.identify(movie, cfg["min_net_gradient"], box, threaded=False)
            if len(identifications) == 0:
                raise ValueError("Picasso detected no molecules; inspect detection/camera parameters")
            cameras = {"Baseline": camera["baseline"], "Sensitivity": camera["sensitivity"], "Gain": camera["gain"], "Qe": 1.0}
            locs = api.fit(movie, cameras, identifications, box)
            info = info + [{"Generated by": "MorSTORM / official Picasso MLE", "Pixelsize": pixel,
                            "Box Size": box, "Min. Net Gradient": cfg["min_net_gradient"], **cameras}]
            # Use Picasso's own writer, including standard localization sanity checks.
            io.save_locs(str(output), locs, info)
        finally:
            if hasattr(movie, "close"): movie.close()
    elif cfg["backend"] == "thunderstorm":
        # ImageJ macro uses a separate JVM and batch mode, with no MIJ dependency.
        fiji = Path(cfg["fiji_dir"]).resolve()
        ij = sorted((fiji / "jars").glob("ij-*.jar"), key=_version)
        plugins = list((fiji / "plugins").glob("*Thunder*STORM*.jar")) + list((fiji / "plugins").glob("*Thunder*Storm*.jar"))
        if not ij or not plugins:
            raise FileNotFoundError("Fiji with Thunder_STORM.jar required")
        java = cfg.get("java_executable")
        if not java:
            candidates = list((fiji / "java").glob("**/bin/java.exe")) + list((fiji / "java").glob("**/bin/java"))
            java = str(candidates[-1]) if candidates else "java"
        macro = resource("thunderstorm.ijm")
        settings = output.with_suffix(".thunderstorm-settings.txt")
        lines = [str(inp).replace("\\", "/"), str(output).replace("\\", "/"),
                 cfg["camera_options"], cfg["analysis_options"]]
        if any("\n" in s or "\r" in s for s in lines):
            raise ValueError("ThunderSTORM macro parameters must each occupy one line")
        settings.write_text("\n".join(lines), encoding="utf-8")
        # Explicit plugin entry jar; exact ImageJ version precedes other jars.
        cp = os.pathsep.join([str(resource("morstorm-morphology.jar")), str(ij[-1]), str(plugins[0]), str(fiji / "jars" / "*")])
        with output.with_suffix(".thunderstorm.log").open("w", encoding="utf-8") as log:
            # ThunderSTORM/ImageJ macro menus require AWT, including in batch mode.
            encoded = [base64.b64encode(str(s).encode("utf-8")).decode("ascii") for s in (macro, settings)]
            subprocess.run([java, "-Djava.awt.headless=false", "-Dfile.encoding=UTF-8", "-Dplugins.dir=" + str(fiji),
                            "-cp", cp, "MorstormThunderstorm", "--base64", *encoded],
                           stdout=log, stderr=subprocess.STDOUT, check=True,
                           timeout=cfg.get("timeout_seconds", 3600))
        if not output.is_file():
            raise RuntimeError("ThunderSTORM produced no CSV; inspect .thunderstorm.log")
    else:
        raise ValueError("backend must be picasso or thunderstorm")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("settings")
    args = parser.parse_args()
    with open(args.settings, encoding="utf-8-sig") as f:
        localize(json.load(f))


if __name__ == "__main__": main()
