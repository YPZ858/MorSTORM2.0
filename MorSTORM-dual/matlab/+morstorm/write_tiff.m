function write_tiff(path,image)
f=Tiff(path,'w'); cleanup=onCleanup(@()f.close());
tags=struct('ImageLength',size(image,1),'ImageWidth',size(image,2),...
    'Photometric',Tiff.Photometric.MinIsBlack,'BitsPerSample',32,'SamplesPerPixel',1,...
    'SampleFormat',Tiff.SampleFormat.IEEEFP,'PlanarConfiguration',Tiff.PlanarConfiguration.Chunky,...
    'Compression',Tiff.Compression.None,'RowsPerStrip',size(image,1));
f.setTag(tags); f.write(single(image));
end
