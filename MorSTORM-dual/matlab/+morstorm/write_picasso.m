function write_picasso(t, metadata, folder)
% Preserve the original compound dataset schema and non-coordinate fields.
raw=h5read(metadata.source,'/locs'); pixel=metadata.pixel_size_nm;
for axis={'x','y','z'}
    a=axis{1};
    if isfield(raw,a)
        divisor=pixel; if strcmp(a,'z'), divisor=1; end
        raw.(a)=reshape(cast(t.([a,'_nm'])/divisor,'like',raw.(a)),size(raw.(a)));
    end
end
target=fullfile(folder,'picasso_corrected.hdf5'); copyfile(metadata.source,target);
file=H5F.open(target,'H5F_ACC_RDWR','H5P_DEFAULT'); closeFile=onCleanup(@()H5F.close(file));
dataset=H5D.open(file,'/locs'); closeDataset=onCleanup(@()H5D.close(dataset));
type=H5D.get_type(dataset); closeType=onCleanup(@()H5T.close(type));
H5D.write(dataset,type,'H5S_ALL','H5S_ALL','H5P_DEFAULT',raw);
[parent,name]=fileparts(metadata.source); sidecar=fullfile(parent,[name,'.yaml']);
yaml=fullfile(folder,'picasso_corrected.yaml');
if isfile(sidecar), copyfile(sidecar,yaml); else, f=fopen(yaml,'w'); fclose(f); end
f=fopen(yaml,'a','n','UTF-8'); cleanup=onCleanup(@()fclose(f));
fprintf(f,'\n---\nGenerated by: MorSTORM 0.5.0rc1\nPixelsize: %.17g\n',pixel);
end
